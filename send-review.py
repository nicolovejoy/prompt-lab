"""Email session review via Claude API + Resend."""

import json
import os
import sys
from datetime import datetime

import heartbeat
from claude_api import SONNET, call_claude, describe_elapsed, get_client, load_env
from store import get_store

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "web"))
from day_helper import lab_days_ago  # noqa: E402
import email_style as es  # noqa: E402
from html import escape  # noqa: E402


def review_windows():
    """The email's two windows, on the lab's clock.

    "Today" is *yesterday's completed lab-day*, never the run date: the job
    fires at 2:30am, when the run date structurally has no summaries yet —
    asking for "today" is how the email said "no new work" on days with 25
    prompts across 4 projects.
    """
    return {
        "review_day": lab_days_ago(1),
        "week_since": lab_days_ago(7),
    }


_PROJECTS = {
    "type": "array",
    "items": {
        "type": "object",
        "properties": {
            "project": {"type": "string", "description": "Project name, as given in the data"},
            "paragraphs": {
                "type": "array",
                "items": {"type": "string"},
                "description": "Plain-text paragraphs, usually one; no HTML or markdown",
            },
        },
        "required": ["project", "paragraphs"],
    },
}

# The model returns content only; render_review() owns the markup (R10), so
# the look is fixed, testable, and carries the shared palette and the
# machine-voice mark.
REVIEW_TOOL = {
    "name": "generate_review",
    "description": "Return the review's content: the two sections, grouped by project.",
    "input_schema": {
        "type": "object",
        "properties": {
            "today": {**_PROJECTS, "description": "Today section: one entry per project"},
            "today_note": {
                "type": "string",
                "description": "One line, only when there is no data for today; otherwise empty",
            },
            "week": {**_PROJECTS, "description": "This Week section: one entry per project"},
        },
        "required": ["today", "week"],
    },
}


def _clean_projects(entries):
    out = []
    for e in entries or []:
        if not isinstance(e, dict):
            continue
        name = str(e.get("project") or "").strip()
        paras = [" ".join(str(p).split()) for p in (e.get("paragraphs") or [])]
        paras = [p for p in paras if p]
        if name and paras:
            out.append((name, paras))
    return out


def review_subject(date, is_weekly):
    """The subject is built here, never by the model: left to the model it
    drifted nightly across date formats and dashes ("Work recap — 5 Nov 2026",
    "Work recap – Tuesday 3 November 2026", "30-day review")."""
    d = datetime.strptime(date, "%Y-%m-%d")
    kind = "Week recap" if is_weekly else "Work recap"
    return f"{kind} · {d:%a} {d.day} {d:%b}"


def render_review(content, date, is_weekly):
    """(subject, html, text) from the model's structured content.

    Raises ValueError when there is nothing to send: an empty email that
    looks sent is the "absence recorded as nothing" shape.
    """
    subject = review_subject(date, is_weekly)
    today = _clean_projects(content.get("today"))
    note = " ".join(str(content.get("today_note") or "").split())
    week = _clean_projects(content.get("week"))
    if not today and not week and not note:
        raise ValueError("review content has no sections")
    sections = [("Today", today, note), ("This Week", week, "")]
    if is_weekly:
        sections.reverse()

    h2 = "font-size:18px;font-weight:bold;margin:0 0 12px"
    h3 = "font-size:16px;font-weight:bold;margin:16px 0 4px"
    p_style = f"font-size:14px;line-height:1.5;color:{es.TEXT_SECONDARY};margin:0 0 8px"
    html_parts, text_parts = [], []
    for i, (title, projects, empty_note) in enumerate(sections):
        if i:
            html_parts.append(f"<hr style='border:none;border-top:1px solid {es.BORDER};margin:20px 0'>")
            text_parts.append("")
        html_parts.append(f"<h2 style='{h2}'>{escape(title)}</h2>")
        text_parts += [title.upper(), ""]
        if not projects:
            line = (empty_note if title == "Today" else "") or "Nothing recorded."
            html_parts.append(f"<p style='{p_style}'>{escape(line)}</p>")
            text_parts.append(line)
            continue
        for name, paras in projects:
            html_parts.append(f"<h3 style='{h3}'>{escape(name)}</h3>")
            html_parts += [f"<p style='{p_style}'>{escape(p)}</p>" for p in paras]
            text_parts.append(name)
            text_parts += paras
            text_parts.append("")
    footer = f"{date} · Generated by Prompt-Labs"
    html_parts.append(
        f"<p style='font-size:12px;color:{es.MUTED};margin:24px 0 0'>"
        f"{escape(footer)} · {es.machine_mark_html()}</p>")
    text = "\n".join(text_parts).rstrip() + f"\n\n--\n{footer} · {es.MACHINE_MARK}\n"
    return subject, es.document("".join(html_parts), title=subject), text


def build_prompt(daily_summaries_1d, weekly_summaries, weekly_rollups, is_weekly):
    def format_summaries(summaries):
        lines = []
        for ds in summaries:
            counts = f" ({ds.get('prompt_count') or 0} prompts, {ds.get('session_count') or 0} sessions)"
            lines.append(f"[{ds['date']}] {ds['project']}{counts}: {ds['summary']}")
        return chr(10).join(lines) or "(none)"

    def format_rollups(rollups):
        if not rollups:
            return "(none)"
        lines = []
        for r in rollups:
            lines.append(f"[{r['project']} / week of {r['week_start']}] {r['narrative']}")
        return chr(10).join(lines)

    rollup_section = ""
    if weekly_rollups:
        rollup_section = f"""

== Weekly rollups (pre-synthesized) ==

{format_rollups(weekly_rollups)}
"""

    user_msg = f"""Date: {datetime.now().strftime('%Y-%m-%d')}

== Last 24 hours ==

Daily summaries ({len(daily_summaries_1d)}):
{format_summaries(daily_summaries_1d)}

== This week (7 days) ==

Daily summaries ({len(weekly_summaries)}):
{format_summaries(weekly_summaries)}{rollup_section}"""

    # The weekly section LEADS on a weekly send, but it does not get a bigger
    # sentence budget — "more depth" is what used to license three fat
    # paragraphs per project. Depth here means themes and direction, not words.
    weekly_emphasis = """
- The weekly section leads today: themes, trajectory, and what's coming next.
  Same sentence budget per project as Today — depth is about direction, not length""" if is_weekly else ""

    system = f"""You write a short email recapping recent work.

The reader is Nico, who did this work with you. "We" means the two of you —
write in first person plural. Where Nico acted alone — a decision, a design
call, a hands-on test — name him: "Nico chose the Studio model". Never address
him as "you".

Two sections:
1. **Today** — the last 24 hours
2. **This Week** — the 7-day period: themes and direction, not a longer list

How to write:
- One entry per project within each section; the project name is its own
  field, so don't repeat it as a label at the start of the paragraph
- Avoid acronyms and initialisms — use the plain words instead: "branches" not
  "PRs", "the automated tests" not "CI", "a hands-on run-through" not "a UX
  smoke". Never expand one in parentheses; just don't reach for it
- Prefer concepts and mental models over jargon and tool names. Say what a
  thing does, not what it is called
- Keep sentences short. Split anything running past ~30 words
- Name the substance: what we built, what specifically broke and what now
  prevents it, what shipped and where, what's next. "Final review caught a bug"
  is not enough — say what the bug was
- Active voice: "we reorganized the Settings page", never "the Settings page
  was reorganised"
- 2-4 sentences per project, in both sections
- Never cite issue or PR numbers. Describe the thing itself
- No verdict on the day — drop "a productive session", "a tidy cleanup", "a
  small but impactful fix". State what happened; he judges it
- No process narration — which tab, which dashboard flow, which button. The
  outcome is the news
- Keep ambiguity rather than smoothing it: "started (continued?)" is better
  than a confident guess
- If there's no data for today, leave Today empty and say so in today_note,
  one line{weekly_emphasis}

Return content only, through the tool. The layout, headings and footer are
added for you. Paragraphs are plain text: no HTML, no markdown, no bullets.
Usually one paragraph per project.
"""

    return system, user_msg


def send_email(subject, html, text):
    import urllib.request

    api_key = os.environ.get("RESEND_API_KEY")
    if not api_key:
        print("Error: RESEND_API_KEY not set", file=sys.stderr)
        sys.exit(1)

    from_email = os.environ.get("REVIEW_FROM_EMAIL")
    to_email = os.environ.get("REVIEW_TO_EMAIL")
    if not from_email or not to_email:
        print("Error: REVIEW_FROM_EMAIL and REVIEW_TO_EMAIL must be set in .env", file=sys.stderr)
        sys.exit(1)

    payload = json.dumps({
        "from": from_email,
        "to": [to_email],
        "subject": subject,
        "html": html,
        "text": text,
    }).encode()

    req = urllib.request.Request(
        "https://api.resend.com/emails",
        data=payload,
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
            "User-Agent": "prompt-lab/1.0",
        },
    )

    # Returns None on failure rather than exiting: the caller still has a
    # generated review worth persisting, and dying here is what hid a 403 for
    # 60 nights — the snapshot never landed, so the DB looked like the job had
    # stopped running instead of failing at the last step.
    try:
        with urllib.request.urlopen(req) as resp:
            return json.loads(resp.read())
    except urllib.error.HTTPError as e:
        body = e.read().decode()
        print(f"Resend API error {e.code}: {body}", file=sys.stderr)
        return None


def main():
    dry_run = "--dry-run" in sys.argv

    # Load environment
    load_env()

    # Exercises the Resend path only — no Claude call, so verifying a
    # from-address or API-key change is free and takes a second rather than
    # two minutes of generation.
    if "--test-send" in sys.argv:
        body = "Test send from send-review.py. If this arrived, Resend is configured correctly."
        if send_email("Prompt Lab — review email test send", es.page(body), body) is None:
            sys.exit(1)
        print("Test send OK.")
        return

    if not os.environ.get("ANTHROPIC_API_KEY"):
        print("Error: ANTHROPIC_API_KEY not found. Set it in .env.local", file=sys.stderr)
        sys.exit(1)

    # Saturday = more reflective weekly tone; always fetch both windows
    today = datetime.now()
    is_weekly = today.weekday() == 5
    today_str = today.strftime("%Y-%m-%d")
    w = review_windows()

    # Reads come from the merged store: processed tables in Turso carry every
    # machine's summaries, so the email covers all work no matter which
    # machine sends it. The raw tier is machine-local by invariant and must
    # never be read here — that's how the email said "no new work" on busy
    # days. Turso being unreachable raises and kills the run: no email, a
    # stale artifact, and the #45 heartbeat catches it — never a confidently
    # empty email.
    store = get_store("turso")
    daily_summaries_1d = store.get_daily_summaries(
        since=w["review_day"], until=w["review_day"])
    weekly_summaries = store.get_daily_summaries(since=w["week_since"])
    weekly_rollups = store.get_weekly_rollups(since=w["week_since"])
    store.close()

    # Guard against the #56 shape: Turso a night behind while this machine's
    # raw tier already has the day's prompts. Reading a *count* (never
    # content) from the local store is not the raw-tier-content read the
    # invariant forbids — it never reaches the email. No try/except: a
    # failure to open or query the local store should fail this stage exactly
    # like any other unhandled error, not be swallowed into "no activity".
    if not daily_summaries_1d:
        local_store = get_store("sqlite")
        local_count = local_store.count_prompts_on(w["review_day"])
        local_store.close()
        if local_count > 0:
            print(
                f"Error: Turso has no daily_summaries for {w['review_day']}, but "
                f"this machine logged {local_count} local prompt(s) that day. "
                f"Refusing to send an empty review — sync likely hasn't caught up.",
                file=sys.stderr,
            )
            sys.exit(1)

    if not weekly_summaries and not weekly_rollups:
        # Stays a plain return, not an error: the guard above already fails
        # loudly if the review day has local prompts Turso hasn't seen. A
        # whole missing week needs Turso itself to be dark that long, and
        # that's the #45 review-email artifact heartbeat's job to catch.
        print("No summaries or rollups found for the period.")
        return

    system, user_msg = build_prompt(daily_summaries_1d, weekly_summaries,
                                     weekly_rollups, is_weekly)

    client = get_client()
    result = call_claude(client, model=SONNET, system=system, user_msg=user_msg,
                         tool=REVIEW_TOOL, max_tokens=16384)

    try:
        subject, html, text = render_review(result["parsed"], today_str, is_weekly)
    except ValueError as e:
        print(f"Error: {e}; nothing sent. Raw tool input: "
              f"{json.dumps(result['parsed'])[:500]}", file=sys.stderr)
        sys.exit(1)

    print(f"Generated review in "
          f"{describe_elapsed(result['duration_ms']/1000, result['awake_ms']/1000)} "
          f"({result['input_tokens']}+{result['output_tokens']} tokens)")
    print(f"Subject: {subject}")
    print(f"Model: {SONNET}")
    print(f"Mode: {'weekly (Saturday)' if is_weekly else 'daily'} — both 1d + 7d windows")

    if dry_run:
        print(f"\n{'=' * 60}")
        print(text)
        print(f"{'=' * 60}")
        print("(dry run, not sent)")
        return

    email_result = send_email(subject, html, text)
    if email_result is None:
        print("Send FAILED — persisting the review anyway.", file=sys.stderr)
    else:
        print(f"Sent (id: {email_result.get('id', '?')})")

    # Persist the review
    store = get_store()
    store.migrate()
    store.save_review_snapshot(
        review_type="weekly_email" if is_weekly else "daily_email",
        date=today_str, subject=subject,
        content_html=html, content_text=text,
        model=SONNET, input_tokens=result["input_tokens"],
        output_tokens=result["output_tokens"],
        # The heartbeat grades this, not the row: a failed send still writes
        # the snapshot, so a row alone cannot see a last-step failure.
        sent_id=(email_result.get("id") or "unknown") if email_result is not None else None,
    )
    store.close()

    # Gated on the send, not on reaching this line. The 60-night outage looked
    # exactly like a healthy run right up to Resend's 403 — a heartbeat that
    # fired on "the process finished" would have reported fresh throughout.
    if email_result is not None:
        heartbeat.ping("review")

    # Non-zero last, after the snapshot is safe, so launchd records the failure.
    if email_result is None:
        sys.exit(1)


if __name__ == "__main__":
    main()
